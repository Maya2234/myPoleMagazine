-- 7. making review trustworthy, and checking it ---------------------------------------
-- Two separate things decide whether a suggestion has to pass review, and neither of them is the
-- review screen itself.
--
-- a) the status a client asks for. submitEntry() sends 'approved' when the account is an admin and
--    'pending' otherwise - but that choice is made in the browser, so the database has to make it
--    too, or review is optional in practice. A trigger is the right tool: unlike a policy it cannot
--    be circumvented from the client, and it does not need to know which insert policy is in
--    place. However a row arrives, anything from a non-admin lands as pending, and submitted_by is
--    pinned to the real caller so nobody can file a suggestion in someone else's name.
--
--    From this editor, or any script holding the service role key, there is no signed-in dancer
--    (auth.uid() is null), so seeding approved entries by hand still does exactly what it says.

create or replace function public.force_entry_status()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is not null and not public.is_admin() then
    new.status := 'pending';
    new.submitted_by := auth.uid();
  end if;
  return new;
end $$;

drop trigger if exists dictionary_entries_force_status on public.dictionary_entries;
create trigger dictionary_entries_force_status
  before insert on public.dictionary_entries
  for each row execute function public.force_entry_status();

-- b) the policies on public.dictionary_entries. Approving a suggestion is an update on someone
--    else's row, so they have to let an admin see pending rows and change them. Those policies live
--    in this project rather than the repo, so look before trusting the queue. Adding policies here
--    is additive on purpose: permissive policies are OR-ed together, so the ones below can only
--    widen access and cannot break the submitter's own view of their pending suggestion.
--
-- Check what is already there first:
--
--   select policyname, cmd, roles, qual, with_check
--     from pg_policies
--    where schemaname = 'public' and tablename = 'dictionary_entries';
--
-- If the queue still says "All caught up" while a suggestion is pending, the select policy is the
-- reason. If a dancer can approve someone else's suggestion, an existing update policy is too loose
-- and has to be dropped by name - the policies below will not tighten anything.

drop policy if exists dictionary_entries_admin_read on public.dictionary_entries;
create policy dictionary_entries_admin_read on public.dictionary_entries for select to authenticated
  using (status = 'approved' or submitted_by = auth.uid() or public.is_admin());

drop policy if exists dictionary_entries_admin_update on public.dictionary_entries;
create policy dictionary_entries_admin_update on public.dictionary_entries for update to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists dictionary_entries_admin_delete on public.dictionary_entries;
create policy dictionary_entries_admin_delete on public.dictionary_entries for delete to authenticated
  using (public.is_admin());


-- 8. checking it afterwards -----------------------------------------------------------
-- Who is an admin, and with profiles.is_admin agreeing:--
--   select a.user_id, p.username, p.is_admin, a.granted_at
--     from public.admins a join public.profiles p on p.id = a.user_id;
--
-- What the browser may now write on profiles - update should list four columns, not the table:
--
--   select grantee, privilege_type, column_name
--     from information_schema.column_privileges
--    where table_name = 'profiles' and grantee = 'authenticated' and privilege_type = 'UPDATE'
--    order by column_name;
--
--   select grantee, privilege_type from information_schema.role_table_grants
--    where table_name = 'profiles' and grantee = 'authenticated';
--
-- Every is_admin in the database and what it contains - the surest way to see what a policy is
-- actually calling, and what to look at if the drop or the replace above ever objects:
--
--   select p.oid::regprocedure as signature, p.prorettype::regtype as returns,
--          p.prosecdef as security_definer, pg_get_functiondef(p.oid) as definition
--     from pg_proc p join pg_namespace n on n.oid = p.pronamespace
--    where n.nspname = 'public' and p.proname = 'is_admin';
--
-- If approving an entry throws "permission denied for table dictionary_entries" the table grant
-- itself is missing - that is the README's step 2, not this file.
