-- Admin membership, and closing the hole that let any dancer promote themselves.
--
-- Run this once in the Supabase SQL editor, after the base tables and supabase/social.sql exist
-- (section 4 grants update on poling_since and avatar, which social.sql adds). It is written to be
-- safe to run again: nothing already in the database is deleted or renamed. If section 4 stops with
-- "column poling_since does not exist", run supabase/social.sql first and then run this file again
-- from the top - the parts before it have already done their work and will report no change.
--
-- Why this file exists
-- --------------------
-- profiles.is_admin is a column on a row its owner may update, and the README's setup grants
-- update on every table to authenticated. So any signed-in dancer could set is_admin = true on
-- themselves and start publishing dictionary entries with no review - the flag was doing the job of a
-- permission while living somewhere the client could write it. Row level security cannot restrict
-- *columns*; only grants and triggers can. The fix is therefore three things together:
--
--   1. the role moves to its own table, public.admins, which no client can read or write;
--   2. public.is_admin() answers "is the caller an admin?" for the policies to use;
--   3. the client's update on public.profiles is narrowed to the four columns the app really
--      writes, so is_admin can no longer be set from the browser.
--
-- profiles.is_admin stays, kept in step by a trigger, because the app reads it
-- (js/store.js -> toUser) and any policy in this project that already tests that column must keep
-- working. It becomes a mirror of public.admins rather than something anyone can set - including by
-- hand: promoting someone is section 6 from now on, not an edit to that column.
--
-- This project already has a public.is_admin() function, so section 2 keeps the name and signature
-- it already has and only changes what it reads: every policy that already calls is_admin()
-- switches to the new table on its own. (Adding a second, argument-taking overload instead makes a
-- bare call ambiguous - Postgres answers "function public.is_admin() is not unique".)
--
-- Nothing here makes anyone an admin: the first one has to come from this editor, because there is
-- nobody to authorise it yet. Section 6 has that one statement. Every system bootstraps its first
-- administrator by hand; the point of the rest of this file is that it is the only time you have to.


-- 1. the role, in its own table ----------------------------------------------------
-- One row per admin. No client is granted anything on it and row level security is on with no
-- policies, so through the API this table reads as empty and refuses every write. Only the
-- functions below - which run as their owner - can change it.

create table if not exists public.admins (
  user_id uuid primary key references public.profiles (id) on delete cascade,
  granted_by uuid references public.profiles (id) on delete set null,
  granted_at timestamptz not null default now(),
  note text
);

alter table public.admins enable row level security;

-- Who granted or removed what, and when. Deleting the admins row would otherwise lose that.
create table if not exists public.admin_audit (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  username text,
  action text not null check (action in ('grant', 'revoke')),
  actor uuid,
  at timestamptz not null default now()
);

alter table public.admin_audit enable row level security;


-- 2. the question the policies ask -------------------------------------------------
-- security definer, so it can read public.admins on behalf of a caller who cannot. Called with no
-- argument - the shape that already exists here - it answers for the signed-in dancer (auth.uid()).
--
-- The name and argument list are deliberate. Your policies call is_admin() with no argument, so
-- replacing the function rather than adding an overload is what lets them switch over untouched.
-- An earlier copy of this file created public.is_admin(uuid), which made every bare call ambiguous;
-- the drop below clears it. Dropping is safe either way: if anything in the project still depended
-- on that overload, Postgres refuses the drop and says so instead of breaking it.

drop function if exists public.is_admin(uuid);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.admins a where a.user_id = auth.uid());
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;


-- 3. keep the old column in step ---------------------------------------------------
-- Anything already reading profiles.is_admin - the app, and any policy in this project - carries on
-- working, because that column now follows this table instead of the other way round.
--
-- The delete branch is written to be quiet: deleting an account removes its admins row through the
-- cascade in the same command, and there is no profile left to mirror. Whether that update matches
-- no row or is refused because the row is already being deleted, both mean the same thing here.

create or replace function public.sync_profile_admin_flag()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    update public.profiles set is_admin = true where id = new.user_id;
  else
    begin
      update public.profiles set is_admin = false where id = old.user_id;
    exception when others then
      null;
    end;
  end if;
  return null;
end $$;

drop trigger if exists admins_sync_flag on public.admins;
create trigger admins_sync_flag
  after insert or delete on public.admins
  for each row execute function public.sync_profile_admin_flag();

-- Whatever is already flagged in profiles becomes a real admin row, and the trigger sets the flag
-- again for them - so a project that promoted someone by hand before this file ran keeps them.
-- This is the step that carries an existing admin over, which is why the whole file is run at once:
-- between section 2 and here the answer is "nobody", and only because both statements are in the
-- same batch does no screen ever see that.
insert into public.admins (user_id, note)
select id, 'migrated from profiles.is_admin'
  from public.profiles
 where is_admin
on conflict (user_id) do nothing;


-- 4. close the column the browser could write --------------------------------------
-- Table privileges and column privileges are independent in Postgres: revoking is_admin alone would
-- change nothing while the table-wide update from the README is still there. So the table grant
-- goes, and only the columns the app actually writes come back by name:
--
--   js/store.js  setPrivacy()  - is_private
--                renameMe()    - username
--                saveProfile() - avatar, poling_since, city, home_studio_id, instagram
--
-- avatar and poling_since arrive with supabase/social.sql, city and home_studio_id with
-- supabase/studios.sql, and instagram with supabase/instagram.sql - and each of those files repeats
-- this list, because re-running any one of them is what puts the list back. A new writable column on
-- profiles belongs in every file that names the list, or the app can save it only until somebody
-- re-runs one of the others.
--
-- Insert goes too: profile rows are created by the trigger on auth.users, never by the browser.
-- (If a profile row is ever missing, js/store.js explains that instead of trying to create one.)
--
-- The same revoke is worth doing to any other table holding a trusted column, for the same reason.

revoke update, insert on public.profiles from authenticated;
grant update (username, is_private, poling_since, avatar, city, home_studio_id, instagram)
  on public.profiles to authenticated;

-- Reading stays as it was - the app needs is_admin in the row it renders.
-- delete stays as it was: supabase/delete-account.sql removes the row as a security definer
-- function, which is the only safe place for it.


-- 5. promoting someone, from the app -------------------------------------------------
-- Both refuse unless the caller is already an admin. From this SQL editor there is no signed-in
-- dancer at all (auth.uid() is null) and the editor is already behind dashboard credentials, so
-- that is allowed through on purpose - it is how the first admin is made, and how you would put
-- things right if the last admin ever lost their account.
--
-- Give a username rather than an id so the statement reads like the thing you mean.

create or replace function public.grant_admin(p_username text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  caller uuid := auth.uid();
  target uuid;
  handle text;
begin
  if caller is not null and not public.is_admin() then
    raise exception 'Admins only.';
  end if;

  select id, username into target, handle
    from public.profiles where lower(username) = lower(btrim(p_username));
  if target is null then
    raise exception 'No dancer called %.', p_username;
  end if;

  insert into public.admins (user_id, granted_by, note)
  values (target, caller, 'granted via grant_admin')
  on conflict (user_id) do nothing;

  /* Already an admin: nothing changed, so nothing to record. */
  if not found then
    return;
  end if;

  insert into public.admin_audit (user_id, username, action, actor)
  values (target, handle, 'grant', caller);
end $$;

create or replace function public.revoke_admin(p_username text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  caller uuid := auth.uid();
  target uuid;
  handle text;
  others int;
begin
  if caller is not null and not public.is_admin() then
    raise exception 'Admins only.';
  end if;

  select id, username into target, handle
    from public.profiles where lower(username) = lower(btrim(p_username));
  if target is null then
    raise exception 'No dancer called %.', p_username;
  end if;

  /* Never remove the last admin. Otherwise the review queue is unreachable again and fixing it
   * means coming back into this editor - the state this file exists to get you out of. */
  select count(*) into others from public.admins where user_id <> target;
  if others = 0 and exists (select 1 from public.admins where user_id = target) then
    raise exception 'That is the only admin. Make someone else an admin first.';
  end if;

  delete from public.admins where user_id = target;

  insert into public.admin_audit (user_id, username, action, actor)
  values (target, handle, 'revoke', caller);
end $$;

revoke all on function public.grant_admin(text) from public;
grant execute on function public.grant_admin(text) to authenticated;
revoke all on function public.revoke_admin(text) from public;
grant execute on function public.revoke_admin(text) to authenticated;


